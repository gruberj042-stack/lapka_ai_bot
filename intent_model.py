# =========================
# ОБУЧЕНИЕ НАМЕРЕНИЯМ
# =========================

vectorizer = TfidfVectorizer()

X = vectorizer.fit_transform(texts)

model = LogisticRegression()

model.fit(X, labels)


# =========================
# ОПРЕДЕЛЕНИЕ НАМЕРЕНИЯ
# =========================

def predict_intent(text):
    vector = vectorizer.transform([text])

    prediction = model.predict(vector)

    return prediction[0]


# =========================
