PRODUCT_KEYWORDS = {

    "🦴 Канат «Грызун»": [
        "канат",
        "грызун",
        "веревка",
        "верёвка",
    ],

    "🥎 Мяч «Бум»": [
        "мяч",
        "бум",
        "апорт",
    ],

    "🧸 Лисёнок-пищалка": [
        "лисенок",
        "лисёнок",
        "лис",
        "пищалка",
    ],

    "⭕ Кольцо «Зубастик»": [
        "кольцо",
        "зубастик",
    ],

    "🧩 Головоломка «Умник»": [
        "головоломка",
        "умник",
        "развивающая",
        "развивающая игрушка",
    ],
}


def predict_product(text):

    text = text.lower()

    for product, keywords in PRODUCT_KEYWORDS.items():

        for keyword in keywords:

            if keyword in text:
                return product

    return None


